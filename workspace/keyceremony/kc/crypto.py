G = 2
# MODP-14 is a safe-prime group: the prime-order subgroup generated by G2=2^2
# has prime order QP=(q-1)/2. Feldman VSS needs the share field to equal the
# commitment group's exponent group, so shares/coefficients live in Z_QP and
# commitments are (G2)^c. This is the standard safe-prime Feldman setup.
QP = (q - 1) // 2
G2 = pow(G, 2, q)


def rand_below(mod: int) -> int:
    """Uniform random integer in [0, mod), rejection sampled."""
    return secrets.randbelow(mod)


# Secret-sharing field = prime-order subgroup of the MODP commitment group.
F_P = QP


def rand_scalar() -> int:
    return rand_below(F_P)


# ---------------------------------------------------------------------------
# Canonical JSON / hashing
# ---------------------------------------------------------------------------

def dumps(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


def b64e(b: bytes) -> str:
    import base64

    return base64.b64encode(b).decode("ascii")


def b64d(s: str) -> bytes:
    import base64

    return base64.b64decode(s.encode("ascii"), validate=True)


def digest(obj) -> bytes:
    return hashlib.sha256(dumps(obj).encode("utf-8")).digest()


def digest_hex(obj) -> str:
    return digest(obj).hex()


# ---------------------------------------------------------------------------
# HKDF (RFC 5869, HMAC-SHA256)
# ---------------------------------------------------------------------------

def hkdf(ikm: bytes, length: int = 32, info: bytes = b"", salt: bytes = b"") -> bytes:
    prk = hmac.new(salt or b"\x00" * 32, ikm, hashlib.sha256).digest()
    out, t, i = b"", b"", 1
    while len(out) < length:
        t = hmac.new(prk, t + info + bytes([i]), hashlib.sha256).digest()
        out += t
        i += 1
    return out[:length]


# ---------------------------------------------------------------------------
# Feldman-verifiable Shamir secret sharing
# ---------------------------------------------------------------------------

class Dealer:
    """Generates shares of a secret with verifiable commitments.

    coeffs = [secret, a1, ..., a_(t-1)] over the Ed25519 scalar field.
    commitments[j] = g^coeffs[j] mod q, so any share (i, s_i) can be
    checked publicly with g^s_i == prod_j C[j]^(i^j).
    """

    def __init__(self, threshold: int, indices: list[int], secret: int | None = None):
        if threshold < 2:
            raise ValueError("threshold must be >= 2: no single person may rebuild a key")
        if len(indices) < threshold:
            raise ValueError("need at least threshold participants")
        self.t = threshold
        self.indices = list(indices)
        self.secret = rand_scalar() if secret is None else secret % F_P
        self.coeffs = [self.secret] + [rand_scalar() for _ in range(threshold - 1)]
        self.commitments = [pow(G2, c, q) for c in self.coeffs]

    def _poly(self, x: int) -> int:
        y = 0
        for c in reversed(self.coeffs):
            y = (y * x + c) % F_P
        return y

    def shares(self) -> dict[int, int]:
        return {i: self._poly(i) for i in self.indices}

    @staticmethod
    def verify_share(index: int, value: int, commitments: list[int]) -> bool:
        lhs = pow(G2, value, q)
        # Polynomial exponents: arithmetic in Z_QP.
        xs, rhs = 1, 1
        for c in commitments:
            rhs = (rhs * pow(c, xs, q)) % q
            xs = (xs * index) % F_P
        return hmac.compare_digest(str(lhs), str(rhs))  # constant-time compare


def lagrange_coeff(index: int, indices: list[int], x: int = 0) -> int:
    num = den = 1
    for j in indices:
        if j == index:
            continue
        num = num * (x - j) % F_P
        den = den * (index - j) % F_P
    return num * pow(den, F_P - 2, F_P) % F_P


def reconstruct(share_map: dict[int, int]) -> int:
    """Reconstruct f(0) from a *verified* set of shares (requires >= t)."""
    indices = list(share_map.keys())
    s = 0
    for i in indices:
        s = (s + share_map[i] * lagrange_coeff(i, indices)) % F_P
    return s


# ---------------------------------------------------------------------------
# Envelope sealing to a device key (static ECDH-like KEM in the MODP group)
# ---------------------------------------------------------------------------

def gen_signing_keypair() -> tuple[bytes, bytes]:
    """Ed25519 root signing keypair: (seed32, public32)."""
    seed = os.urandom(32)
    return seed, ed25519.public_from_secret(seed)


def gen_seal_keypair() -> tuple[int, int]:
    """Sealing keypair in the prime-order subgroup: (private x, public G2^x)."""
    x = secrets.randbelow(QP - 1) + 1
    return x, pow(G2, x, q)


def seal(pub: int, plaintext: bytes, context: bytes) -> dict:
    """KEM: ephemeral y -> shared = pub^y; DEM: stream + HMAC tag.

    Ciphertext is plaintext XOR SHA256 keystream; the tag binds context so a
    share envelope cannot be replayed into a different ceremony/device.
    """
    y = secrets.randbelow(QP - 1) + 1
    eph = pow(G2, y, q)
    shared = pow(pub, y, q)
    k = hkdf(shared.to_bytes(256, "big"), 64, info=b"kc-seal-v1|" + context)
    nonce = os.urandom(32)
    stream = hashlib.sha256(k[:32] + nonce).digest()
    # Extend stream to plaintext length
    out = bytearray()
    counter = 0
    data = plaintext
    while len(out) < len(data):
        out.extend(hashlib.sha256(k[:32] + nonce + counter.to_bytes(8, "big")).digest())
        counter += 1
    ct = bytes(a ^ b for a, b in zip(data, out))
    tag = hmac.new(k[32:], nonce + ct + context, hashlib.sha256).digest()
    return {"eph": eph, "nonce": nonce, "ct": ct, "tag": tag, "context": context}


def open_seal(priv: int, env: dict) -> bytes:
    shared = pow(int(env["eph"]), priv, q)
    context = bytes(env["context"])
    k = hkdf(shared.to_bytes(256, "big"), 64, info=b"kc-seal-v1|" + context)
    expected = hmac.new(k[32:], bytes(env["nonce"]) + bytes(env["ct"]) + context,
                        hashlib.sha256).digest()
    if not hmac.compare_digest(expected, bytes(env["tag"])):
        raise ValueError("sealed envelope authentication failed")
    out = bytearray()
    counter = 0
    while len(out) < len(env["ct"]):
        out.extend(hashlib.sha256(k[:32] + bytes(env["nonce"]) + counter.to_bytes(8, "big")).digest())
        counter += 1
    return bytes(a ^ b for a, b in zip(bytes(env["ct"]), out))


def envelope_to_json(env: dict) -> dict:
    return {
        "eph": str(env["eph"]),
        "nonce": b64e(env["nonce"]),
        "ct": b64e(env["ct"]),
        "tag": b64e(env["tag"]),
        "context": b64e(env["context"]),
    }


def envelope_from_json(obj: dict) -> dict:
    return {
        "eph": int(obj["eph"]),
        "nonce": b64d(obj["nonce"]),
        "ct": b64d(obj["ct"]),
        "tag": b64d(obj["tag"]),
        "context": b64d(obj["context"]),
    }


def int_to_bytes(n: int) -> bytes:
    length = max(1, (n.bit_length() + 7) // 8)
    return n.to_bytes(length, "big")


def bytes_to_int(b: bytes) -> int:
    return int.from_bytes(b, "big")
