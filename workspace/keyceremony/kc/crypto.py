"""Cryptographic primitives used by the ceremony orchestrator.

Contents:
  * q / G       - RFC 3526 2048-bit MODP group (prime order subgroup is not
                  prime, but this only acts as a Feldman-commitment /
                  sealing group; soundness is DLP-based and shares live in
                  a separate prime field f_p = Ed25519 scalar field).
  * Feldman VSS - verifiable Shamir secret sharing over the Ed25519 scalar
                  field, with commitments in the MODP group.
  * HKDF, seal/open envelope (KEM + HMAC-DEM, post-quantum-style hybrid
                  unneeded here; pure stdlib).
  * canonical JSON encoding + hashing.
"""

